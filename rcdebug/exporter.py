"""
Markdown Security & QA Audit Report generator for rcdebug (--export <file.md>).
"""

from __future__ import annotations

from pathlib import Path

from .models import SEVERITY_ORDER, AuditSession, Finding, SeverityFilter, format_filter_label, matches_filter


def generate_markdown_report(session: AuditSession, filter_level: SeverityFilter = None) -> str:
    filtered_findings: list[Finding] = [
        f for f in session.findings if matches_filter(f.severity, filter_level)
    ]
    # Sort findings strictly by (severity_tier, catalog_rank_asc, confidence_desc)
    filtered_findings.sort(key=lambda f: f.sort_key())

    counts = {"CRITICAL": 0, "WARN": 0, "INFO": 0}
    for f in filtered_findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    lines: list[str] = [
        "# rcdebug — Roblox Security & Performance Audit Report",
        "",
        "## 1. Executive Summary",
        "",
        "| Field | Value |",
        "| :--- | :--- |",
        f"| **Audit Mode** | `{session.mode.upper()}` |",
        f"| **Target** | `{session.target_name}` |",
        f"| **Session Timestamp** | `{session.started_at}` |",
        f"| **Severity Filter** | `{format_filter_label(filter_level) if filter_level else 'ALL'}` |",
        f"| **Total Findings** | **{len(filtered_findings)}** (`{counts['CRITICAL']}` Critical, `{counts['WARN']}` Warn, `{counts['INFO']}` Info) |",
        "",
    ]

    lines.extend([
        "## 2. Findings Overview",
        "",
    ])

    if not filtered_findings:
        lines.append("_No findings recorded matching the active filter criteria._")
        lines.append("")
    else:
        lines.extend([
            "| # | Severity | Category | Title | Instance Path |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for idx, f in enumerate(filtered_findings, start=1):
            lines.append(
                f"| {idx} | **{f.severity}** | `{f.category}` | {f.title} | `{f.path}` |"
            )
        lines.append("")

        lines.extend([
            "## 3. Detailed Security & Architectural Findings",
            "",
        ])

        for idx, f in enumerate(filtered_findings, start=1):
            lines.extend([
                f"### 3.{idx} [{f.severity}] {f.title}",
                "",
                f"- **Instance Path:** `{f.path}`",
                f"- **Category:** `{f.category}`",
                f"- **Detected At:** `{f.timestamp}`",
                f"- **Architectural Flaw:** {f.flaw}",
                f"- **Malicious Client Abuse Vector:** {f.abuse}",
                f"- **Recommended Server-Side Fix:** {f.fix}",
                "",
            ])
            if f.code_example:
                lines.extend([
                    "```luau",
                    f.code_example.strip(),
                    "```",
                    "",
                ])

    if session.remote_traffic:
        lines.extend([
            "## 4. Remote Traffic Profiler Summary",
            "",
            "| Remote Path | Class | Total Calls | Peak Rate (calls/s) | Last Rate (calls/s) | Cooldown Flag |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for stat in sorted(
            session.remote_traffic.values(),
            key=lambda s: (-s.peak_rate_per_sec, -s.total_calls),
        ):
            flag = "NEEDS DEBOUNCE" if stat.has_cooldown_warning else "OK"
            lines.append(
                f"| `{stat.remote_path}` | `{stat.remote_type}` | {stat.total_calls} | "
                f"{stat.peak_rate_per_sec:.1f}/s | {stat.last_rate_per_sec:.1f}/s | **{flag}** |"
            )
        lines.append("")

    if session.memory_snapshots:
        lines.extend([
            "## 5. Instance & Memory Diffing Timeline",
            "",
            "| Snapshot Time | Elapsed (s) | Workspace Instances | Player Instances | Total Memory (MB) |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for snap in session.memory_snapshots:
            lines.append(
                f"| `{snap.timestamp}` | {snap.elapsed_sec:.1f}s | "
                f"{snap.workspace_instances} | {snap.player_instances} | {snap.total_memory_mb:.2f} MB |"
            )
        lines.append("")

    lines.extend([
        "---",
        "_Generated by **rcdebug (Revan Cool Debugger)** v1.0.0_",
        "",
    ])

    return "\n".join(lines)


def export_markdown_report(
    session: AuditSession,
    output_path: str | Path,
    filter_level: str | None = None,
) -> Path:
    dest = Path(output_path).expanduser().resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)
    report_md = generate_markdown_report(session, filter_level=filter_level)
    dest.write_text(report_md, encoding="utf-8")
    return dest
